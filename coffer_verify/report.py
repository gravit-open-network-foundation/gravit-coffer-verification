#!/usr/bin/env python3
"""Builds REPORT.md from results/ only, so every number in the report is reproducible."""

import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def ts(t: int) -> str:
    return datetime.fromtimestamp(t, timezone.utc).strftime("%Y-%m-%d")


def main() -> None:
    rows, rm_tot, sw_tot, res_tot = [], {}, {}, {"VERIFIED": 0, "INVALID": 0}
    adm_tot, alerts = {}, 0
    for f in sorted((ROOT / "results").glob("*/summary.json")):
        s = json.loads(f.read_text())
        sw = s.get("swap_verification") or {}
        for k, v in s["results"].items():
            rm_tot[k] = rm_tot.get(k, 0) + v
        for k, v in (sw.get("results") or {}).items():
            sw_tot[k] = sw_tot.get(k, 0) + v
        rc = sw.get("reserve_checks") or {}
        res_tot["VERIFIED"] += rc.get("VERIFIED", 0)
        res_tot["INVALID"] += rc.get("INVALID", 0)
        adm = s.get("admin_actions") or {}
        alerts += adm.get("alerts", 0)
        for ob in (adm.get("by_obligation") or {}).values():
            for k, v in ob.items():
                adm_tot[k] = adm_tot.get(k, 0) + v
        frm = s["evidence"].get("from", "pool creation")
        rows.append(f"| `{s['pool'][:8]}…` | {s['evidence']['transactions']} | "
                    f"{frm if isinstance(frm, str) else 'since ' + ts(frm)} | "
                    f"{s['range_manager_updates']} {fmt(s['results'])} | {sw.get('swaps', 0)} {fmt(sw.get('results') or {})} | "
                    f"{rc.get('VERIFIED', 0)}/{rc.get('VERIFIED', 0) + rc.get('INVALID', 0)} | "
                    f"{s['final_state_matches_chain']['result']} |")
    m = ROOT / "results" / "metrics"
    tvl = json.loads((m / "tvl.json").read_text()) if (m / "tvl.json").exists() else None
    vols = sorted(m.glob("volume-*.json"))
    vol = json.loads(vols[-1].read_text()) if vols else None
    lines = [
        "# Coffer × Gravit — verification report",
        "",
        "Independent, read-only verification of the Coffer protocol on Solana from the public ledger.",
        "Generated by `python -m coffer_verify.report` from `results/`; every figure below is",
        "reproduced by CI from the committed evidence. This is not a security audit.",
        "",
        "## Summary",
        "",
        f"- Range-manager transitions checked: **{sum(rm_tot.values())}** — {fmt(rm_tot)}",
        f"- Swaps re-computed (price, fees, surge fee, post-state): **{sum(sw_tot.values())}** — {fmt(sw_tot)}",
        f"- Pool vault balance = LP reserves + protocol fees: **{res_tot['VERIFIED']} of "
        f"{res_tot['VERIFIED'] + res_tot['INVALID']}** checks",
        f"- Admin and protocol actions (COFFER-ADM-01): **{sum(adm_tot.values())}** — {fmt(adm_tot)}; "
        f"debug or withdrawal calls: **{alerts}**",
        "",
        "`INSUFFICIENT` means the ledger did not contain enough data to decide (for example Solana",
        "truncated a transaction's logs, or a pool was created by an earlier program version whose",
        "events the current IDL cannot decode); it is never counted as verified. `RECORDED` actions",
        "are listed with their signer, not judged.",
        "",
        "## Per pool",
        "",
        "| Pool | Transactions | Evidence | Range-manager updates | Swaps | Reserve checks | Replayed state = chain |",
        "|---|---|---|---|---|---|---|",
        *rows,
    ]
    if tvl or vol:
        lines += ["", "## Public metrics (C-02)", ""]
    if tvl:
        lines += [f"- **TVL** at slot {tvl['slot']} ({tvl['fetched_at']}): **${tvl['tvl_usd_lp_reserves']:,.0f}** in LP "
                  f"reserves (${tvl['tvl_usd_including_protocol_fees']:,.0f} including protocol fees owed). Token "
                  f"amounts from the chain; prices from {tvl['price_source']}. Tokens without a price are listed "
                  "in `results/metrics/tvl.json` and not counted."]
    if vol:
        w = vol["window"]
        lines += [f"- **Swap volume** {ts(w['start'])} – {ts(w['end'])} (30 days): **${vol['volume_usd']:,.0f}** over "
                  f"{vol['swaps']:,} swaps; ${vol['of_which_priced_by_stablecoin_leg']:,.0f} of it priced exactly by a "
                  f"USDC/USDT leg, the rest at a current price snapshot. Swap fees paid: ${vol['fees_usd']:,.0f}. "
                  f"Transactions missing from the evidence: {vol['transactions_missing']}."]
    # notes computed from the results, so they stay true when the results change
    surge_checked = surge_nonzero = 0
    for f in (ROOT / "results").glob("*/swaps.jsonl"):
        for line in f.read_text().splitlines():
            r = json.loads(line)["record"]
            if any(o["id"] == "COF-SURGE" and o["result"] == "VERIFIED" for o in r["obligations"]):
                surge_checked += 1
                surge_nonzero += r["event"]["surge_fee_amount"] > 0
    lines += ["", "## Notes", ""]
    lines += [f"- Sell-off window: {surge_checked} swaps sold a token with a sell-off cap; the window accounting and "
              f"the surge fee matched the chain in all of them. The surge fee was non-zero in {surge_checked and surge_nonzero} "
              "of these swaps" + (" — the surge curve itself has therefore not yet been exercised by a real non-zero case."
                                   if surge_nonzero == 0 else ".")]
    if vol and vol["pools"]:
        top, top_v = max(vol["pools"].items(), key=lambda kv: kv[1])
        lines += [f"- Volume concentration: {100 * top_v / vol['volume_usd']:.0f} % of the 30-day volume came from one pool "
                  f"(`{top[:8]}…`). Volume is reported as recorded on chain; this report does not judge who traded or why."]
    lines += ["- Range-manager checks cover the evidence windows only; earlier updates (before 2026-09-11) of pools whose "
              "evidence starts later are not covered."]
    (ROOT / "REPORT.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def fmt(d: dict) -> str:
    return "(" + ", ".join(f"{v} {k.lower()}" for k, v in sorted(d.items())) + ")" if d else ""


if __name__ == "__main__":
    main()
